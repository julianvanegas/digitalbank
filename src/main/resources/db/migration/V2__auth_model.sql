-- Separa seguridad (cuenta, sesión, verificaciones) de los datos del cliente.
-- Módulos cubiertos: auth y customer. Las filas ADMIN pasan a user_account; su perfil
-- se archiva en legacy_admin_profile hasta que exista el módulo staff.

-- ============ 1. CATÁLOGOS ============
CREATE TABLE role (
    id   SMALLINT PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE category (
    id   SMALLINT PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE status (
    id          SMALLINT PRIMARY KEY,
    category_id SMALLINT NOT NULL REFERENCES category (id),
    code        VARCHAR(30) NOT NULL,
    CONSTRAINT uk_status_category_code UNIQUE (category_id, code)
);

CREATE TABLE challenge_purpose (
    id           SMALLINT PRIMARY KEY,
    code         VARCHAR(30) NOT NULL UNIQUE,
    ttl_minutes  INTEGER NOT NULL CHECK (ttl_minutes > 0),
    max_attempts INTEGER NOT NULL CHECK (max_attempts > 0)
);

CREATE TABLE document_type (
    id   SMALLINT PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

