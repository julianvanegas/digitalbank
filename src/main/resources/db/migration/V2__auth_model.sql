-- ============ 2. CUENTA, SESIÓN Y VERIFICACIONES ============
CREATE TABLE user_account (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               VARCHAR(254) NOT NULL UNIQUE,
    password_hash       VARCHAR(255) NOT NULL,
    password_changed_at TIMESTAMP NOT NULL,
    role_id             SMALLINT NOT NULL REFERENCES role (id),
    status_id           SMALLINT NOT NULL REFERENCES status (id),
    failed_attempts     INTEGER NOT NULL DEFAULT 0,
    last_login_at       TIMESTAMP,
    created_at          TIMESTAMP NOT NULL,
    CONSTRAINT uk_user_account_id_role UNIQUE (id, role_id)
);

CREATE INDEX idx_user_account_status_last_login ON user_account (status_id, last_login_at);

CREATE TABLE auth_session (
    user_account_id BIGINT PRIMARY KEY REFERENCES user_account (id),
    jti             VARCHAR(255) NOT NULL UNIQUE,
    issued_at       TIMESTAMP NOT NULL,
    expires_at      TIMESTAMP NOT NULL
);

CREATE TABLE verification_challenge (
    id              UUID PRIMARY KEY,
    user_account_id BIGINT NOT NULL REFERENCES user_account (id),
    purpose_id      SMALLINT NOT NULL REFERENCES challenge_purpose (id),
    code_hash       VARCHAR(255) NOT NULL,
    expires_at      TIMESTAMP NOT NULL,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_challenge_account_purpose UNIQUE (user_account_id, purpose_id)
);

-- ============ 3. VALIDACIONES PREVIAS (la migración falla si hay datos fuera del mapeo) ============
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM customers WHERE role NOT IN ('USER', 'ADMIN')) THEN
        RAISE EXCEPTION 'customers.role con valores fuera de USER/ADMIN: revisar a mano';
    END IF;
    IF EXISTS (SELECT 1 FROM customers WHERE status NOT IN ('ACTIVE', 'PENDING_VALIDATION', 'BLOCKED', 'INACTIVE')) THEN
        RAISE EXCEPTION 'customers.status con valores desconocidos: revisar a mano';
    END IF;
    IF EXISTS (SELECT 1 FROM customers WHERE role = 'USER' AND document_type NOT IN ('CC', 'CE', 'PASSPORT')) THEN
        RAISE EXCEPTION 'customers.document_type con valores fuera de CC/CE/PASSPORT: revisar a mano';
    END IF;
END $$;

-- ============ 4. UNA CUENTA POR CADA FILA DE customers ============
INSERT INTO user_account (email, password_hash, password_changed_at, role_id, status_id,
                          failed_attempts, last_login_at, created_at)
SELECT c.email,
       c.password_hash,
       now(),
       CASE c.role WHEN 'USER' THEN 1 WHEN 'ADMIN' THEN 2 END,
       CASE
           WHEN c.role = 'ADMIN' THEN
               CASE c.status
                   WHEN 'ACTIVE'             THEN 5
                   WHEN 'PENDING_VALIDATION' THEN 6
                   WHEN 'BLOCKED'            THEN 7
                   WHEN 'INACTIVE'           THEN 5  -- no existe para personal: revisión manual
               END
           ELSE
               CASE c.status
                   WHEN 'ACTIVE'             THEN 1
                   WHEN 'PENDING_VALIDATION' THEN 2
                   WHEN 'INACTIVE'           THEN 3
                   WHEN 'BLOCKED'            THEN 4
               END
       END,
       c.failed_attempts,
       c.last_login,
       now()
FROM customers c
ORDER BY c.id;

-- Perfil de los administradores: se conserva hasta que exista staff_member
CREATE TABLE legacy_admin_profile AS
SELECT ua.id AS user_account_id, c.name, c.document_type, c.document_number, c.phone, c.birth_date
FROM customers c
JOIN user_account ua ON ua.email = c.email
WHERE c.role = 'ADMIN';

